#!/usr/bin/env python3
"""Generate display-only medal/map/stage labels from pinned regional BCData."""
import argparse
import csv
import hashlib
import json
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[1]
# Matches upstream MapNames and SaveDocument's serialized map groups.
GROUPS = {'rn': 0, 'rs': 1000, 'rc': 2000, 'rna': 13000, 'rb': 14000,
          'rv': 7000, 'ra': 24000, 'rh': 25000, 'rca': 27000,
          'rnd': 34000, 'rd': 16000, 'rq': 31000, 'rsr': 37000}


def generate(cache):
    versions = json.loads((ROOT / 'tools/game_data_manifest.json').read_text())['regions']
    arrays, hashes = [], {}

    def array(key, rows):
        def value(row):
            return escape(row).replace('\\', '\\\\').replace('"', '\\"').replace("'", "\\'").replace('\t', '\\t').replace('\n', '\\n')
        arrays.append(f'    <string-array name="{key}">\n' + '\n'.join(
            '        <item>"' + value(row) + '"</item>' for row in rows) + '\n    </string-array>')

    for region, lang in [('en', 'en'), ('tw', 'tw'), ('jp', 'ja'), ('kr', 'ko')]:
        directory = cache / region / versions[region]['version'] / 'resLocal'
        hashes[region] = {'version': versions[region]['version'], 'sha256': {}}

        def read(name, delimiter):
            path = directory / name
            hashes[region]['sha256'][name] = hashlib.sha256(path.read_bytes()).hexdigest()
            with path.open(encoding='utf-8-sig', newline='') as stream:
                return list(csv.reader(stream, delimiter=delimiter, quoting=csv.QUOTE_NONE))

        medals = read('medalname.tsv', '\t')
        array(f'medal_names_{region}', ['\t'.join(row[:2]) for row in medals])
        delimiter = ',' if region == 'jp' else '|'
        maps = {int(row[0]): row[1].strip() for row in read('Map_Name.csv', delimiter) if len(row) >= 2 and row[0].strip().isdigit()}
        for chapter in range(3):
            rows = read(f'StageName{chapter}_{lang}.csv', delimiter)
            array(f'story_stage_names_{region}_{chapter}', [rows[45 - i if i < 46 else i][0].strip() for i in range(48)])
        for code, base in GROUPS.items():
            rows = read(f'StageName_{code.upper()}_{lang}.csv', delimiter)
            array(f'map_names_{region}_{code}', [maps.get(base + i, '') for i in range(len(rows))])
            stages = []
            for row in rows:
                names = []
                for cell in row:
                    if cell.strip() in ('＠', '@'): break
                    names.append(cell.strip())
                while names and not names[-1]: names.pop()
                stages.append('\t'.join(names))
            array(f'stage_names_{region}_{code}', stages)
    output = '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <!-- Generated by tools/generate_editor_catalog.py; regional game text. -->\n' + '\n'.join(arrays) + '\n</resources>\n'
    for locale in ['values', 'values-zh-rCN']:
        (ROOT / 'app/src/main/res' / locale / 'editor_catalog.xml').write_text(output)
    (ROOT / 'tools/editor_catalog_manifest.json').write_text(json.dumps(hashes, ensure_ascii=False, indent=2) + '\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cache', type=Path, default=Path.home() / '.local/share/bcsfe/game_data')
    generate(parser.parse_args().cache)

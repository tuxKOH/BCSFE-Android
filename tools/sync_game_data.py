#!/usr/bin/env python3
"""Generate offline Android rules from pinned, regional upstream BCData caches.

Usage: python3 tools/sync_game_data.py [--cache ~/.local/share/bcsfe/game_data]
Download/extract the matching official BCData releases into REGION/VERSION first.
Only fields consumed by the Android editor are bundled; no account/save data.
"""
from __future__ import annotations

import argparse
import base64
import csv
import gzip
import hashlib
import json
from pathlib import Path

VERSIONS = {"en": "15.7.0", "jp": "16.0.3", "tw": "15.7.0", "kr": "15.7.0"}
ROOT = Path(__file__).resolve().parents[1]


def numeric_rows(path: Path, *, delimiter: str = ",", header: bool = False):
    with path.open(encoding="utf-8-sig", newline="") as stream:
        rows = csv.reader(stream, delimiter=delimiter)
        if header:
            next(rows)
        return [row for row in rows if row and row[0].strip()]


def generate(cache: Path):
    tables: dict[str, str] = {}
    declarations: list[str] = []
    snapshots: list[str] = []
    provenance = json.loads((ROOT / "tools/game_data_sources.json").read_text())
    if {region: source["version"] for region, source in provenance["regions"].items()} != VERSIONS:
        raise ValueError("Update extraction provenance before changing the regional versions")
    manifest = {"source": "https://git.battlecatsmodding.org/fieryhenry/BCData",
                "upstream_parser": provenance["upstream_parser"],
                "provenance": provenance, "regions": {}, "historical": {}}
    max_cats = 0
    for key, version in list(VERSIONS.items()) + [("jp_157", "15.7.4")]:
        region = key.split("_")[0]
        directory = cache / region / version / "DataLocal"
        hashes = {}

        def read(name, **kwargs):
            path = directory / name
            hashes[name] = hashlib.sha256(path.read_bytes()).hexdigest()
            return numeric_rows(path, **kwargs)

        def pack(rows):
            raw = "\n".join(",".join(str(int(cell or 0)) for cell in row) for row in rows)
            if raw in tables:
                return tables[raw]
            name = f"TABLE_{len(tables)}"
            tables[raw] = name
            encoded = base64.b64encode(gzip.compress(raw.encode("ascii"), mtime=0)).decode()
            chunks = [encoded[i:i + 112] for i in range(0, len(encoded), 112)]
            declarations.append(f"    private static final int[][] {name} = decode(\n"
                                + " +\n".join(f'            "{part}"' for part in chunks) + ");")
            return name

        unit = read("unitbuy.csv")
        max_cats = max(max_cats, len(unit))
        buy = pack([[row[i] for i in (13, 18, 49, 50, 51, 56, 22)] for row in unit])
        picture = pack([[row[0], row[2]] for row in read("nyankoPictureBookData.csv")])
        drops = pack([[row[2], row[1]] for row in read("drop_chara.csv", header=True)])
        limits = pack(read("unitlimit.csv"))
        gifts = pack(read("rankGift.csv"))
        skills = []
        for row in read("SkillAcquisition.csv", header=True):
            for i in range(2, len(row) - 1, 14):
                if int(row[i] or 0):
                    skills.append([row[0], row[i], int(row[i + 1] or 0) or 1])
        talents = pack(skills)
        # Match MissionConditions.get_conditions: progress_count is row[3].
        missions = pack([[row[0], row[3]] for row in read("Mission_Condition.csv", header=True)])
        maps = pack([[row[0], row[1]] for row in read("Map_option.csv", header=True)])
        schemes = pack([[row[0]] for row in read("schemeItemData.tsv", delimiter="\t", header=True)])
        orb_path = directory / "equipmentlist.json"
        hashes["equipmentlist.json"] = hashlib.sha256(orb_path.read_bytes()).hexdigest()
        orb_rows = json.loads(orb_path.read_text())["ID"]
        orbs = pack([[row["gradeID"], row["content"], row.get("attribute", -1)] for row in orb_rows])
        major, minor, patch = map(int, version.split("."))
        value = major * 10000 + minor * 100 + patch
        snapshots.append(f"    private static final Snapshot {key.upper()} = new Snapshot({value}, "
                         + ", ".join((buy, picture, drops, limits, gifts, talents, missions, maps, schemes, orbs)) + ");")
        destination = manifest["regions"] if key == region else manifest["historical"]
        destination[key] = {"version": version, "cat_count": len(unit), "orb_count": len(orb_rows), "sha256": hashes}

    source = '''package io.github.tuxkoh.bcsfe.core;

/** Generated by tools/sync_game_data.py from upstream BCData. Do not edit tables. */
final class UpstreamGameData {
    private UpstreamGameData() {}
'''
    source += f"    static final int MAX_CAT_COUNT = {max_cats};\n\n"
    source += "\n\n".join(declarations) + "\n\n" + "\n".join(snapshots)
    source += '''

    static Snapshot forRegion(SaveDocument.Region region) {
        return switch (region) { case EN -> EN; case JP -> JP; case TW -> TW; case KR -> KR; };
    }

    static Snapshot forVersion(SaveDocument.Region region, int version) {
        return region == SaveDocument.Region.JP && version <= JP_157.version ? JP_157 : forRegion(region);
    }

    static Snapshot matching(SaveDocument.Region region, int version) {
        Snapshot snapshot = forVersion(region, version);
        // Keep the existing exact 15.5.0/15.6.0 tables. Other compatible
        // revisions use the next regional BCData snapshot, like upstream's
        // GameDataGetter.get_version, without rewriting the save version.
        if (version == 150500 || version == 150600) return null;
        return GameVersions.supported(region, version) ? snapshot : null;
    }

    static final class Snapshot {
        final int version;
        final int[][] unitBuy, pictureBook, drops, unitLimits, rankGifts, talents, missions, maps, schemes, orbs;

        Snapshot(int version, int[][] unitBuy, int[][] pictureBook, int[][] drops, int[][] unitLimits,
                 int[][] rankGifts, int[][] talents, int[][] missions, int[][] maps, int[][] schemes, int[][] orbs) {
            this.version=version; this.unitBuy=unitBuy; this.pictureBook=pictureBook;
            this.drops=drops; this.unitLimits=unitLimits; this.rankGifts=rankGifts;
            this.talents=talents; this.missions=missions; this.maps=maps; this.schemes=schemes; this.orbs=orbs;
        }

        int talentMaxLevel(int cat, int ability) {
            for (int[] row : talents) if (row[0] == cat && row[1] == ability) return row[2];
            return 0;
        }

        int valueById(int[][] rows, int id, int column, int fallback) {
            for (int[] row : rows) if (row[0] == id) return row[column];
            return fallback;
        }
    }

    private static int[][] decode(String encoded) {
        try (java.util.zip.GZIPInputStream input = new java.util.zip.GZIPInputStream(
                new java.io.ByteArrayInputStream(java.util.Base64.getDecoder().decode(encoded)))) {
            String csv = new String(IoStreams.readAll(input), java.nio.charset.StandardCharsets.US_ASCII);
            String[] lines = csv.split("\\n");
            int[][] rows = new int[lines.length][];
            for (int i=0; i<lines.length; i++) {
                String[] cells=lines[i].split(","); rows[i]=new int[cells.length];
                for (int j=0; j<cells.length; j++) rows[i][j]=Integer.parseInt(cells[j]);
            }
            return rows;
        } catch (java.io.IOException error) { throw new ExceptionInInitializerError(error); }
    }
}
'''
    (ROOT / "app/src/main/java/io/github/tuxkoh/bcsfe/core/UpstreamGameData.java").write_text(source)
    (ROOT / "tools/game_data_manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")
    for region, data in manifest["regions"].items():
        print(f"{region}: {data['version']}, {data['cat_count']} cats")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cache", type=Path, default=Path.home() / ".local/share/bcsfe/game_data")
    generate(parser.parse_args().cache)
